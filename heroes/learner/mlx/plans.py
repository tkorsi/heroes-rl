"""Plans the MLX backend executes: whole-game prefixes and joined loss windows."""
import bisect


# The planner finalizes these integer-only sequences before consumers see them.
# They stay on the CPU and are never mutated by MLX execution.
_CPU_PLAN_METADATA_KEYS = frozenset({
    "group_first_use", "jobs", "cpu_positions", "cpu_reuse", "attribute_ends",
    "group_ends", "descriptor_ends", "delta_ends", "object_ends", "first_ends", "second_ends",
})


def _cpu_plan_metadata(key, value):
    if key == "group_first_use":
        if isinstance(value, tuple) and all(isinstance(group, tuple) for group in value):
            return value
        return tuple(tuple(group) for group in value)
    return tuple(value)


def _compact_groups(groups):
    # Row indices are generated by mx.arange; only pooled groups consume scale.
    # Segments belonged to the generic tree gradient and are not kernel inputs.
    result = []
    for kind, indices, values, count in groups:
        unused = {"segments"} if kind == "pooled" else {"rows", "scale"} if kind == "ordered" else {"rows"} if kind == "text" else set()
        result.append((kind, indices, {key: value for key, value in values.items() if key not in unused}, count))
    return result


def _prefix_plan(history):
    """The whole game as one no-gradient plan, including its sparse map CNN."""
    return _portable_plan(history.plan(0, history.frame_count))

def _portable_plan(original):
    result = {key: value for key, value in original.items() if key not in ("_arenas", "decisions")}
    result["decision_count"] = len(original["decisions"])
    result["groups"] = _compact_groups(original["groups"])
    return result

def _joined_plan(histories, windows, rollouts):
    """One plan for all loss windows of a minibatch, sharing identical nodes."""
    from ..plan import History
    nodes, frames, shared, mapped, layout, all_decisions = [], [], {}, {}, [], []

    def node(history_index, root):
        key = (history_index, root)
        if key in mapped:
            return mapped[key]
        kind, value, children = histories[history_index].nodes[root]
        if kind in ("text", "number"):
            mapped_children = []
        else:
            value = node(history_index, value)
            mapped_children = [node(history_index, child) for child in children]
        canonical = (kind, tuple(float(x).hex() for x in value) if kind == "number" else value,
                     tuple(mapped_children))
        found = shared.get(canonical)
        if found is None:
            found = len(nodes)
            nodes.append((kind, value, mapped_children))
            shared[canonical] = found
        mapped[key] = found
        return found

    for window in windows:
        index, start, end = window.rollout_index, window.start_seq, window.end_seq
        history = histories[index]
        decisions = [rollouts[index].decisions[i] for i in window.sample_indices]
        wanted, offset = set(decisions), len(frames)
        for frame_index in range(start, end + 1):
            frame = history.frames[frame_index]
            root = -1 if frame["root"] < 0 else node(index, frame["root"])
            game_map = frame["map"]
            if game_map is not None:
                game_map = {**game_map, "own": node(index, game_map["own"])}
            conditionals = None
            if frame_index in wanted:
                conditionals = []
                for conditional in frame["conditionals"]:
                    conditional = dict(conditional)
                    if conditional["kind"] == "categorical":
                        conditional["roots"] = [node(index, r) for r in conditional["roots"]]
                    else:
                        conditional["root"] = node(index, conditional["root"])
                    conditionals.append(conditional)
            frames.append({"root": root, "map": game_map, "conditionals": conditionals})
        all_decisions.extend(offset + item - start for item in decisions)
        layout.append((index, start, offset, len(frames)))
    plan = History(nodes, frames).plan(0, len(frames), all_decisions)
    sequences = [{"history": index, "start": start, "left": bisect.bisect_left(plan["jobs"], left),
                  "right": bisect.bisect_left(plan["jobs"], right)} for index, start, left, right in layout]
    return _portable_plan(plan), sequences

def _active_parameters(plan, parameter_order):
    """Match Adam's skip for absent gradients, including the custom tree backward."""
    prefixes = {"gru.", "value."}
    for kind, _, data, _ in plan["groups"]:
        if kind == "text" and data:
            prefixes.update(("byte.", "text_gru."))
        elif kind == "number":
            prefixes.add("number.")
        elif kind in ("ordered", "pooled"):
            prefixes.add("tree.")
            if kind == "ordered" and "children" in data:
                prefixes.add("ordered.")
    if plan["maps"] is not None:
        prefixes.update(("terrain.", "road.", "object_encoder.", "map_cnn.", "map_global."))
    for kind, head in plan["heads"]:
        prefixes.add({"categorical": "policy_query.", "quantity": "quantity."}.get(kind, "coordinate."))
        if "window_memory" in head:
            prefixes.add("window_memory.")
    return [name for name in parameter_order if any(name.startswith(prefix) for prefix in prefixes)]
